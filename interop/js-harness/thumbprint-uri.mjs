#!/usr/bin/env node
// JWK Thumbprint URI interop (L5, RFC 9278) — against panva/jose.
//
//     node interop/js-harness/thumbprint-uri.mjs
//
// Run from anywhere; `jose` resolves because this file sits beside js-harness/node_modules.
//
// `jose` is the only widely used implementation of RFC 9278 in this project's peer set, and it
// is a good peer precisely because it made the same spelling decision independently: the URI
// carries the IANA **Hash Name String** (`sha-256`, hyphen included), while jose's own *algorithm
// argument* is spelled `sha256`. Comparing the two implementations' output as text — not as
// "both parse" — is what makes that agreement worth having.
//
// Every key here is generated by the Rust harness and fed to jose as a JWK, so both sides
// compute a thumbprint of identical octets.

import { execFileSync } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { calculateJwkThumbprint, calculateJwkThumbprintUri } from 'jose'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..', '..')
const HARNESS = path.join(ROOT, 'interop', 'rust-harness', 'target', 'release', 'jose-interop')

let checks = 0
const failures = []

function check (ok, detail) {
  checks++
  console.log(`  ${ok ? 'ok  ' : 'FAIL'} ${detail}`)
  if (!ok) failures.push(detail)
}

function rust (args, stdin) {
  return execFileSync(HARNESS, args, { input: stdin, encoding: 'utf8' })
}

// A256KW exercises the `oct` member set (the secret `k`), a different required-member list
// from every asymmetric type here.
const ALGS = ['RS256', 'ES256', 'ES384', 'ES512', 'EdDSA', 'A256KW']
const DIGESTS = [['SHA-256', 'sha256'], ['SHA-384', 'sha384'], ['SHA-512', 'sha512']]

async function main () {
  // The RFC's own example, as a cross-check that neither implementation drifted from the text.
  const rfcVector = {
    kty: 'RSA',
    n: '0vx7agoebGcQSuuPiLJXZptN9nndrQmbXEps2aiAFbWhM78LhWx4cbbfAAtVT86zwu1RK7aPFFxuhDR1L6tSoc_BJECPebWKRXjBZCiFV4n3oknjhMstn64tZ_2W-5JsGY4Hc5n9yBXArwl93lqt7_RN5w6Cf0h4QyQ5v-65YGjQR0_FDW2QvzqY368QQMicAtaSqzs8KJZgnYb9c7d0zgdAZHzu6qMQvRL5hajrn1n91CbOpbISD08qNLyrdkt-bFTWhAI4vMQFh6WeZu0fM4lFd2NcRwr3XPksINHaQ-G_xBniIqbw0Ls1jF44-csFCur-kEgU8awapJzKnqDKgw',
    e: 'AQAB',
    alg: 'RS256',
    kid: '2011-04-29',
  }
  const rfcUri = 'urn:ietf:params:oauth:jwk-thumbprint:sha-256:NzbLsXh8uDCcd-6MNwXF4W_7noWXFZAfHkxZsRGC9Xs'
  check((await joseUri(rfcVector, 'sha256')) === rfcUri, 'jose reproduces the RFC 9278 §6 example URI')
  check(rust(['thumbprint-uri'], JSON.stringify(rfcVector)).trim() === rfcUri,
    'jose-rs reproduces the RFC 9278 §6 example URI')

  for (const alg of ALGS) {
    const jwk = JSON.parse(rust(['gen-key', '--alg', alg]))
    // Optional members must not change the answer: both sides hash the required members only,
    // and adding kid/use/alg is the cheapest test that they really do.
    const decorated = { ...jwk, kid: `kid-${alg}`, use: 'sig', alg }

    for (const [rustHash, joseHash] of DIGESTS) {
      const ours = rust(['thumbprint-uri', '--hash', rustHash], JSON.stringify(jwk)).trim()
      const theirs = await joseUri(jwk, joseHash)
      check(ours === theirs, `${alg} ${rustHash}: URI matches jose byte for byte`)
      check(ours.startsWith(`urn:ietf:params:oauth:jwk-thumbprint:${rustHash.toLowerCase()}:`),
        `${alg} ${rustHash}: the identifier is the IANA Hash Name String`)

      const decoratedOurs = rust(['thumbprint-uri', '--hash', rustHash], JSON.stringify(decorated)).trim()
      const decoratedTheirs = await joseUri(decorated, joseHash)
      check(decoratedOurs === ours && decoratedTheirs === theirs,
        `${alg} ${rustHash}: optional members do not change the thumbprint`)
    }

    // jose's default digest is SHA-256, as RFC 9278 §5 makes mandatory to implement.
    const defaultUri = await calculateJwkThumbprintUri(jwk)
    check(defaultUri === rust(['thumbprint-uri'], JSON.stringify(jwk)).trim(),
      `${alg}: jose's default URI is our SHA-256 URI`)

    // The value inside the URI is the plain thumbprint, on both sides.
    const ours = rust(['thumbprint-uri', '--hash', 'SHA-256'], JSON.stringify(jwk)).trim()
    check(ours.split(':').pop() === (await calculateJwkThumbprint(jwk, 'sha256')),
      `${alg}: URI value equals jose's standalone thumbprint`)
  }

  console.log(`\n${checks} checks, ${failures.length} failures`)
  if (failures.length) {
    for (const failure of failures) console.log(`  - ${failure}`)
    process.exit(1)
  }
}

async function joseUri (jwk, hash) {
  return hash ? calculateJwkThumbprintUri(jwk, hash) : calculateJwkThumbprintUri(jwk)
}

main()
